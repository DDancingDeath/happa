#!/usr/bin/env node
/**
 * Joins the stylesheets listed in www/styles.css (@import order = cascade order)
 * into www/css/app.css, the one stylesheet index.html links (#66): one request
 * at start instead of ~30. Not a bundler: the files are copied as written.
 *
 *   npm run build:css            # write www/css/app.css
 *   node scripts/build-css.js --check   # exit 1 when app.css is out of date
 *
 * Edit the source files in www/css/, then run npm run build:css and commit both.
 */
const fs = require('fs');
const path = require('path');

const WWW = path.join(__dirname, '..', 'www');
const LIST = path.join(WWW, 'styles.css');
const OUT = path.join(WWW, 'css', 'app.css');
const OUT_URL = 'css/app.css';

/** Stylesheet paths (relative to www/) in @import order. */
function cssSources(listSource = fs.readFileSync(LIST, 'utf8')) {
    return [...listSource.matchAll(/@import url\('([^']+)'\)/g)].map((m) => m[1]);
}

/** The app.css text for the current sources (LF line endings). */
function buildCss(sources = cssSources(), read = (rel) => fs.readFileSync(path.join(WWW, rel), 'utf8')) {
    const parts = sources.map((rel) => {
        if (!/^css\/[a-z0-9-]+\.css$/.test(rel) || rel === OUT_URL) throw new Error(`Bad stylesheet in styles.css: ${rel}`);
        const body = read(rel).replace(/\r\n/g, '\n').replace(/\s+$/, '');
        if (/@import|@charset/.test(body)) throw new Error(`${rel}: @import/@charset can't be joined into app.css`);
        return `/* ---- ${rel} ---- */\n${body}\n`;
    });
    return `/* Generated by npm run build:css from the files listed in www/styles.css. Don't edit: edit those files and rebuild. */\n${parts.join('\n')}`;
}

function isUpToDate() {
    if (!fs.existsSync(OUT)) return false;
    return fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === buildCss();
}

module.exports = { cssSources, buildCss, isUpToDate, OUT_URL };

if (require.main === module) {
    if (process.argv.includes('--check')) {
        if (isUpToDate()) {
            console.log('OK: www/css/app.css matches the files in www/styles.css.');
            process.exit(0);
        }
        console.error('www/css/app.css is out of date: run npm run build:css and commit it.');
        process.exit(1);
    }
    fs.writeFileSync(OUT, buildCss());
    console.log(`Wrote www/${OUT_URL} from ${cssSources().length} stylesheets.`);
}
